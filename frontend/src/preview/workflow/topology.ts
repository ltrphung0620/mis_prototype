export interface NodeDefinition {
  id: string;
  sourceNode: string;
  title: string;
  description: string;
  phase: Phase;
  kind: "agent" | "gate" | "system" | "interaction";
  outputs: readonly string[];
  x: number;
  y: number;
  source: string;
}
function node(
  id: string,
  title: string,
  description: string,
  phase: Phase,
  x: number,
  y: number,
  outputs: readonly string[],
  source: string,
  kind: NodeDefinition["kind"] = "agent",
  sourceNode = id,
): NodeDefinition {
  return {
    id,
    sourceNode,
    title,
    description,
    phase,
    x,
    y,
    outputs,
    source,
    kind,
  };
}
